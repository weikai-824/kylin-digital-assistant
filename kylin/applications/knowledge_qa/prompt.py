def grounded_user(style: str = GROUNDING_STYLE_STRICT) -> str:
    """按接地风格返回 GROUNDED_USER 模板（lenient 用于易过度拒答的模型平台）."""
    if style == GROUNDING_STYLE_LENIENT:
        return GROUNDED_USER_LENIENT
    return GROUNDED_USER


